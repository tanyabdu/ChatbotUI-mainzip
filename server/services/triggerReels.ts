export async function transformToTriggerReels(originalScript: string): Promise<{
  transformedScript: string;
  usedTriggers: { name: string; explanation: string }[];
  hookAnalysis: string;
  ctaType: string;
  usedFormulas: string;
}> {
  return withRetry(async () => {
    const response = await deepseek.chat.completions.create({
      model: AI_MODEL,
      messages: [
        {
          role: "system",
          content: SYSTEM_PROMPT,
        },
        {
          role: "user",
          content: `Вот оригинальный сценарий Reels, который нужно переработать в триггерный:\n\n${originalScript}`,
        },
      ],
      temperature: 0.8,
      max_tokens: 6000,
      response_format: { type: "json_object" },
    }, { timeout: 25000 });

    const content = extractContent(response);
    if (!content) {
      throw new Error("Пустой ответ от AI");
    }

    let parsed: any;
    try {
      const cleaned = content.replace(/^```(?:json)?\s*/i, "").replace(/```\s*$/i, "").trim();
      parsed = JSON.parse(cleaned);
    } catch {
      throw new ParseError("AI вернул некорректный формат ответа");
    }

    return {
      transformedScript: parsed.transformedScript || "",
      usedTriggers: parsed.usedTriggers || [],
      hookAnalysis: parsed.hookAnalysis || "",
      ctaType: parsed.ctaType || "",
      usedFormulas: parsed.usedFormulas || "",
    };
  }, "TriggerReels");
}
